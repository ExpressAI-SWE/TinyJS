// Compile the MDX files into Preact components used by the documentation routes.
import { compile } from '@mdx-js/mdx';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';

const content = new URL('../content/', import.meta.url);
const output = new URL('../app/docs/generated/', import.meta.url);
await mkdir(output, { recursive: true });
for (const name of await readdir(content)) {
  if (!name.endsWith('.mdx')) continue;
  const compiled = await compile((await readFile(new URL(name, content), 'utf8')).replace(/\r\n/g, '\n'), { jsxImportSource: 'preact' });
  await writeFile(new URL(name.replace(/\.mdx$/, '.jsx'), output), '// Generated by scripts/docs.mjs; edit content/*.mdx.\n' + String(compiled));
}
